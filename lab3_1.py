# Зчитування двох цілих чисел з консолі
a = int(input("Введіть перше ціле число (a): "))
b = int(input("Введіть друге ціле число (b): "))

# Обчислення
sum_result = a + b
diff_result = a - b
prod_result = a * b

# Виведення результатів
print(f"Сума: {sum_result}")
print(f"Різниця: {diff_result}")
print(f"Добуток: {prod_result}")